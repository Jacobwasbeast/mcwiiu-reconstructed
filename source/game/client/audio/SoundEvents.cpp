SoundEvent* SoundEvents::registerSound(SoundEvent* soundEvent)
{
    soundEvent->setIndex(nextSoundEventId);

    soundEventRegistry.registerMapping(nextSoundEventId, ResourceLocation(soundEvent->getName()), soundEvent);

    ++nextSoundEventId;

    return soundEvent;
}

SoundEvent* SoundEvents::registerSound(const std::wstring& name)
{
    return registerSound(new SoundEvent(name, 16.0f));
}

int SoundEvents::getCount()
{
    return nextSoundEventId;
}

