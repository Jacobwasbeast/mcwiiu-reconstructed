CompoundTag* ItemIdFix::fix(CompoundTag* tag)
{
    if (tag->contains(L"id", Tag::TAG_ANY_NUMERIC))
    {
        int id = tag->getShort(L"id");
        boost::unordered_map<int, std::wstring>::iterator entry = ID_MAP.find(id);

        if (entry != ID_MAP.end())
        {
            tag->putString(L"id", entry->second);
        }
    }

    return tag;
}

