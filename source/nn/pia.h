class ScopedLock
{
public:
    explicit ScopedLock(CriticalSection& criticalSection) : m_criticalSection(criticalSection)
    {
        m_criticalSection.Lock();
    }
    ~ScopedLock() { m_criticalSection.Unlock(); }

private:
    CriticalSection& m_criticalSection;
};
