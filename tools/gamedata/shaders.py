"""Generate the compiled GX2 shader sources from the user's own executable.

The renderer's shader objects and the Mii icon shader files are compiler
output that lives only inside Minecraft.Client.rpx. The recipe names where each
one lives; this module reads them and writes C++ the source includes:

  RendererShaders.inc       every renderer shader object with its program and
                            uniform, sampler and attribute tables
  MiiIconDefaultShader.inc  the bytes of the Mii icon default shader file
  MiiIconExtShader.inc      the bytes of the Mii icon extension shader file

    python tools/gamedata/shaders.py <Minecraft.Client.rpx> <output dir>
"""
import hashlib
import json
import os
import re
import struct
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import rpl  # noqa: E402

ROOT = os.path.dirname(os.path.dirname(HERE))
RECIPE = os.path.join(HERE, "recipe-v688.json")
GX2_TYPES = os.path.join(ROOT, "source", "cafe", "gx2", "gx2Types.h")
GENERATED_NOTE = ("// Generated by tools/prepare.py from your own copy of Minecraft.Client.rpx "
                  "(update %d). Do not edit or commit.\n")

VERTEX_REGISTERS = 52
PIXEL_REGISTERS = 41
VERTEX_FIELDS = ("size", "program", "mode", "uniform_block_count", "uniform_blocks", "uniform_var_count",
                 "uniform_vars", "initial_value_count", "initial_values", "loop_var_count", "loop_vars",
                 "sampler_var_count", "sampler_vars", "attrib_var_count", "attrib_vars", "ring_item_size",
                 "has_stream_out", "stream_out_stride0", "stream_out_stride1", "stream_out_stride2",
                 "stream_out_stride3", "buffer_flags", "buffer_element_size", "buffer_element_count", "buffer")
PIXEL_FIELDS = ("size", "program", "mode", "uniform_block_count", "uniform_blocks", "uniform_var_count",
                "uniform_vars", "initial_value_count", "initial_values", "loop_var_count", "loop_vars",
                "sampler_var_count", "sampler_vars", "buffer_flags", "buffer_element_size",
                "buffer_element_count", "buffer")
PROGRAM_WORDS_PER_LINE = 8
BYTES_PER_LINE = 17


class GenerationError(Exception):
    """The executable does not hold what the recipe describes."""


def load_recipe(path=RECIPE):
    with open(path, encoding="utf-8") as handle:
        return json.load(handle)


def load_enums(path=GX2_TYPES):
    """Map GX2 enum values to their names, read from the source's own header."""
    with open(path, encoding="utf-8") as handle:
        text = handle.read()
    enums = {}
    for prefix in ("GX2_VAR_TYPE_", "GX2_SAMPLER_TYPE_", "GX2_SHADER_MODE_"):
        table = {}
        for name, value in re.findall(r"\b(%s\w+)\s*=\s*(\d+)" % prefix, text):
            table.setdefault(int(value), name)
        if not table:
            raise GenerationError("no %s values in %s" % (prefix, path))
        enums[prefix] = table
    enums["bool"] = {0: "GX2_FALSE", 1: "GX2_TRUE"}
    return enums


def enum_name(enums, prefix, value):
    try:
        return enums[prefix][value]
    except KeyError:
        raise GenerationError("no %s name for value %d" % (prefix, value))


def check_executable(path, recipe):
    """Return the executable's bytes if it is the version the recipe describes."""
    expected = recipe["executable"]
    size = os.path.getsize(path)
    if size != expected["size"]:
        raise GenerationError("%s is %d bytes; update v%d's executable is %d bytes"
                              % (path, size, recipe["update_version"], expected["size"]))
    with open(path, "rb") as handle:
        data = handle.read()
    digest = hashlib.sha256(data).hexdigest()
    if digest != expected["sha256"]:
        raise GenerationError("%s does not match update v%d (sha256 %s)" % (path, recipe["update_version"], digest))
    return data


def read_object(image, address, kind):
    registers = VERTEX_REGISTERS if kind == "vertex" else PIXEL_REGISTERS
    names = VERTEX_FIELDS if kind == "vertex" else PIXEL_FIELDS
    words = image.words(address, registers + len(names))
    fields = dict(zip(names, words[registers:]))
    fields["registers"] = words[:registers]
    for unsupported in ("uniform_block_count", "initial_value_count", "loop_var_count"):
        if fields[unsupported]:
            raise GenerationError("shader object at 0x%08X has %s %d; the generator does not emit those tables"
                                  % (address, unsupported, fields[unsupported]))
    if fields["buffer"]:
        raise GenerationError("shader object at 0x%08X carries a GX2R buffer pointer" % address)
    if kind == "vertex" and fields["has_stream_out"] not in (0, 1):
        raise GenerationError("shader object at 0x%08X has an invalid stream-out flag" % address)
    return fields


def signed(value):
    return struct.unpack(">i", struct.pack(">I", value))[0]


def uniform_vars(image, address, count, enums):
    rows = []
    for index in range(count):
        name, kind, var_count, offset, block = image.words(address + 20 * index, 5)
        rows.append('    {"%s", %s, %d, 0x%X, %d},' % (image.c_string(name), enum_name(enums, "GX2_VAR_TYPE_", kind),
                                                      var_count, offset, signed(block)))
    return rows


def sampler_vars(image, address, count, enums):
    rows = []
    for index in range(count):
        name, kind, location = image.words(address + 12 * index, 3)
        rows.append('    {"%s", %s, %d},' % (image.c_string(name), enum_name(enums, "GX2_SAMPLER_TYPE_", kind), location))
    return rows


def attrib_vars(image, address, count, enums):
    rows = []
    for index in range(count):
        name, kind, var_count, location = image.words(address + 16 * index, 4)
        rows.append('    {"%s", %s, %d, %d},' % (image.c_string(name), enum_name(enums, "GX2_VAR_TYPE_", kind),
                                                 var_count, location))
    return rows


def program_lines(words):
    lines = []
    for start in range(0, len(words), PROGRAM_WORDS_PER_LINE):
        chunk = words[start:start + PROGRAM_WORDS_PER_LINE]
        lines.append("    " + ", ".join("0x%08X" % word for word in chunk) + ",")
    return lines


def render_shader(image, shader, enums):
    kind = shader["kind"]
    label = "Vertex" if kind == "vertex" else "Pixel"
    base = "g%sShader%s" % (label, shader["name"])
    fields = read_object(image, int(shader["object"], 16), kind)
    if fields["size"] % 4:
        raise GenerationError("%s program size %d is not a whole number of words" % (base, fields["size"]))
    program_symbol = "sg%sShader%sProgram" % (label, shader["name"])
    words = image.words(fields["program"], fields["size"] // 4)
    lines = []

    def table(type_name, suffix, count, rows):
        lines.append("static %s %s%s[%d] = {" % (type_name, base, suffix, count))
        lines.extend(rows)
        lines.append("};")
        return "%s%s" % (base, suffix)

    uniforms = samplers = attribs = "NULL"
    if fields["uniform_var_count"]:
        uniforms = table("GX2UniformVar", "UniformVars", fields["uniform_var_count"],
                         uniform_vars(image, fields["uniform_vars"], fields["uniform_var_count"], enums))
    if fields["sampler_var_count"]:
        samplers = table("GX2SamplerVar", "Samplers", fields["sampler_var_count"],
                         sampler_vars(image, fields["sampler_vars"], fields["sampler_var_count"], enums))
    lines.append("static u32 %s[%d] __attribute__((aligned(GX2_SHADER_ALIGNMENT))) = {" % (program_symbol, len(words)))
    lines.extend(program_lines(words))
    lines.append("};")
    if kind == "vertex" and fields["attrib_var_count"]:
        attribs = table("GX2AttribVar", "AttribVars", fields["attrib_var_count"],
                        attrib_vars(image, fields["attrib_vars"], fields["attrib_var_count"], enums))

    registers = ", ".join("0x%08X" % word for word in fields["registers"])
    common = ("{{%s}, 0x%X, %s, %s, 0, NULL, %d, %s, 0, NULL, 0, NULL, %d, %s"
              % (registers, fields["size"], program_symbol, enum_name(enums, "GX2_SHADER_MODE_", fields["mode"]),
                 fields["uniform_var_count"], uniforms, fields["sampler_var_count"], samplers))
    if kind == "vertex":
        strides = ",".join("0x%08X" % fields["stream_out_stride%d" % i] for i in range(4))
        buffer = ",".join("0x%08X" % fields[k] for k in ("buffer_flags", "buffer_element_size", "buffer_element_count"))
        lines.append("GX2VertexShader %s = %s, %d, %s, %d, %s, {%s}, {%s,NULL}};"
                     % (base, common, fields["attrib_var_count"], attribs, fields["ring_item_size"],
                        enums["bool"][fields["has_stream_out"]], strides, buffer))
    else:
        buffer = ",".join("%d" % fields[k] for k in ("buffer_flags", "buffer_element_size", "buffer_element_count"))
        lines.append("GX2PixelShader %s = %s, {%s,NULL}};" % (base, common, buffer))
    if shader.get("blank_line_after"):
        lines.append("")
    return lines


def render_renderer_shaders(image, recipe, enums):
    lines = []
    for shader in recipe["renderer_shaders"]["shaders"]:
        lines.extend(render_shader(image, shader, enums))
    return "\n".join(lines) + "\n"


def render_bytes(image, address, size):
    data = image.read(address, size)
    lines = []
    for start in range(0, len(data), BYTES_PER_LINE):
        chunk = data[start:start + BYTES_PER_LINE]
        lines.append("    " + ", ".join("0x%02x" % byte for byte in chunk) + ",")
    lines[-1] = lines[-1][:-1]
    return "\n".join(lines) + "\n"


def generate(executable, output_dir, recipe_path=RECIPE, gx2_types=GX2_TYPES):
    """Write every generated shader source into output_dir. Returns
    {file name: sha256 of its contents}."""
    recipe = load_recipe(recipe_path)
    image = rpl.Rpl(check_executable(executable, recipe))
    enums = load_enums(gx2_types)
    note = GENERATED_NOTE % recipe["update_version"]
    outputs = {recipe["renderer_shaders"]["output"]: note + render_renderer_shaders(image, recipe, enums)}
    for item in recipe["shader_files"]:
        outputs[item["output"]] = note + render_bytes(image, int(item["address"], 16), item["size"])
    os.makedirs(output_dir, exist_ok=True)
    hashes = {}
    for name, text in sorted(outputs.items()):
        data = text.encode("utf-8")
        with open(os.path.join(output_dir, name), "wb") as handle:
            handle.write(data)
        hashes[name] = hashlib.sha256(data).hexdigest()
    return hashes


def main(argv):
    if len(argv) != 2:
        sys.exit(__doc__)
    try:
        hashes = generate(argv[0], argv[1])
    except (GenerationError, rpl.RplError, OSError) as error:
        sys.exit("error: %s" % error)
    for name, digest in sorted(hashes.items()):
        print("%s  %s" % (digest, name))


if __name__ == "__main__":
    main(sys.argv[1:])
